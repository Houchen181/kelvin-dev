import subprocess, sys, pyvisa
from pyvisa.constants import Parity
def ctl(*a):
    print("   $ labsim " + " ".join(a), "->", subprocess.run([sys.executable, "-m", "labsim"] + list(a), capture_output=True, text=True).stdout.strip())
rm = pyvisa.ResourceManager("@labsim")
li = rm.open_resource("GPIB0::8::INSTR", timeout=1000)
ctl("power", "li_xx", "off")
try: li.query("*IDN?")
except Exception as e: print("lock-in switched off:", str(e)[:70])
ctl("power", "li_xx", "on"); print("back on:", li.query("SLVL?").strip(), "(power-on default)")
y = rm.open_resource("USB0::0x0B21::0x0039::91T810992::INSTR", timeout=1000)
ctl("unplug", "yoko")
try: y.query("*IDN?")
except Exception as e: print("USB cable pulled:", str(e)[:70])
print("listed now:", [r for r in rm.list_resources() if r.startswith("USB")])
ctl("plug", "yoko")
tc = rm.open_resource("ASRL3::INSTR", baud_rate=57600, data_bits=7, parity=Parity.odd, read_termination="\r\n", write_termination="\r\n")
ctl("fault", "tc", "sensor_openA")
print("open sensor A:", tc.query("KRDG? A").strip(), "RDGST?", tc.query("RDGST? A").strip())
ctl("fault", "tc", "sensor_openA", "off")
tc.close()
ctl("hold", "tc")
try: rm.open_resource("ASRL3::INSTR")
except Exception as e: print("held by another program:", str(e)[:80])
ctl("hold", "tc", "off")
m = rm.open_resource("TCPIP0::192.168.10.30::7180::SOCKET", read_termination="\r\n", write_termination="\r\n")
m.read(); m.read()
m.write("CONF:RAMP:RATE:FIELD 1,0.1,9;:CONF:FIELD:TARG 2;:RAMP")
import time; time.sleep(1.5)
print("AMI ramped at 0.1 T/s (magnet tolerates 0.02 T/s): STATE?", m.query("STATE?").strip(), "(7 = quench)")
